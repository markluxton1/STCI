#!/usr/bin/env python3
"""Independent exact Z4 leading obstruction, F2 rank, and nonlinear jet checks."""
import itertools
import sympy as s
a,b,h,d,A,B,G,D=s.symbols("a b h d A B G D")
coeff=[
 h*(a*h+3*b*b-5*b*d+3*d*d),
 (b-d)*(4*a*h+3*b*b-8*b*d+6*d*d),
 a*(a*h+9*b*b-23*b*d+15*d*d)
]
sub={a:2*A,b:2*B,h:2*G,d:1+2*D}
for expr,expected in zip(coeff,[2*G,2,2*A]):
 p=s.Poly(s.expand((expr-expected).subs(sub)),A,B,G,D)
 assert all(int(c)%4==0 for c in p.coeffs())
print("PASS: universal mod-4 polynomial identities")
classes={}
for aa,gg in itertools.product(range(2),repeat=2):
 v=tuple(int(x.subs({a:2*aa,b:0,h:2*gg,d:1}))%4//2 for x in coeff)
 assert v==(gg,1,aa)
 classes[(aa,gg)]=v
assert len(set(classes.values()))==4
print("PASS: all four classes realized by actual quotient parameters")
# F2 image generated by (1,0,0) and (0,0,1).
im={(x,0,z) for x,z in itertools.product(range(2),repeat=2)}
assert len(im)==4
assert all(tuple((v[i]-classes[(0,0)][i])%2 for i in range(3)) in im for v in classes.values())
assert all(v[1]==1 for v in classes.values())
print("PASS: rank 2, kernel beta, persistent middle coordinate 1")
# Direct truncated substitution of nonlinear adapted coordinate change:
# x'=x+C*y^2+A*x*y, y'=y+D*y^2+B*x.
x,y,t,cc,aa,bb,dd=s.symbols("x y t cc aa bb dd")
# Along x=t*y^2, modulo y^3: x'=(t+cc)*y^2 and y'^2=y^2.
xp=x+cc*y**2+aa*x*y
yp=y+dd*y**2+bb*x
assert s.Poly(s.expand(xp.subs(x,t*y**2)-(t+cc)*yp.subs(x,t*y**2)**2),y).coeff_monomial(y**2)==0
print("PASS: nonlinear adapted-jet transformation through quadratic order")
